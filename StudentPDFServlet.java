
package com.learnhub;

import com.lowagie.text.Document;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Element;
import com.lowagie.text.pdf.PdfWriter;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;

import java.io.IOException;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;

@WebServlet("/StudentPDFServlet")
public class StudentPDFServlet extends HttpServlet {

    @Override
    protected void doGet(HttpServletRequest request,
                         HttpServletResponse response)
            throws ServletException, IOException {

        HttpSession session = request.getSession(false);

        if (session == null
                || session.getAttribute("studentEmail") == null) {

            response.sendRedirect("login.jsp");
            return;
        }

        String email =
                session.getAttribute("studentEmail").toString();

        String sql = "SELECT student_id, name, email, phone, course "
                   + "FROM students WHERE email = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, email);

            try (ResultSet rs = ps.executeQuery()) {

                if (!rs.next()) {
                    response.sendError(
                        HttpServletResponse.SC_NOT_FOUND,
                        "Student details not found."
                    );
                    return;
                }

                int studentId = rs.getInt("student_id");
                String name = rs.getString("name");
                String studentEmail = rs.getString("email");
                String phone = rs.getString("phone");
                String course = rs.getString("course");

                response.setContentType("application/pdf");
                response.setHeader(
                    "Content-Disposition",
                    "attachment; filename=\"LearnHub_Student_Details.pdf\""
                );

                Document document = new Document();

                try {
                    PdfWriter.getInstance(
                        document, response.getOutputStream()
                    );

                    document.open();

                    Font titleFont = FontFactory.getFont(
                        FontFactory.HELVETICA_BOLD, 20
                    );

                    Font headingFont = FontFactory.getFont(
                        FontFactory.HELVETICA_BOLD, 13
                    );

                    Font normalFont = FontFactory.getFont(
                        FontFactory.HELVETICA, 12
                    );

                    Paragraph title = new Paragraph(
                        "LearnHub - Student Details", titleFont
                    );

                    title.setAlignment(Element.ALIGN_CENTER);
                    document.add(title);
                    document.add(new Paragraph(" "));

                    document.add(new Paragraph(
                        "Student ID: " + studentId, normalFont
                    ));

                    document.add(new Paragraph(
                        "Name: " + safe(name), normalFont
                    ));

                    document.add(new Paragraph(
                        "Email: " + safe(studentEmail), normalFont
                    ));

                    document.add(new Paragraph(
                        "Phone: " + safe(phone), normalFont
                    ));

                    document.add(new Paragraph(
                        "Course: " + safe(course), normalFont
                    ));

                    document.add(new Paragraph(" "));
                    document.add(new Paragraph(
                        "Generated by LearnHub", headingFont
                    ));

                } finally {
                    if (document.isOpen()) {
                        document.close();
                    }
                }
            }

        } catch (Exception e) {
            throw new ServletException(
                "Unable to generate student PDF.", e
            );
        }
    }

    private String safe(String value) {
        return value == null || value.trim().isEmpty()
                ? "Not provided" : value;
    }
}

